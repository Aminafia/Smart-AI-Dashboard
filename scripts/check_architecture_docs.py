#!/usr/bin/env python3
"""Generate structural architecture views and check documentation drift.

Uses only the Python standard library.
  python scripts/check_architecture_docs.py --write
  python scripts/check_architecture_docs.py --check
"""
from __future__ import annotations

import argparse
import glob
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "docs" / "generated" / "SOURCE_INVENTORY.md"
PROJECT_MAP = ROOT / "docs" / "generated" / "DOTNET_PROJECT_DEPENDENCIES.md"
DOC_ROOTS = (ROOT / "docs",)
TOP_LEVEL_DOCS = (ROOT / "README.md",)
BT = chr(96)
FENCE = BT * 3


def working_tree_paths() -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=ROOT,
        check=True,
        stdout=subprocess.PIPE,
    )
    paths = [item for item in result.stdout.decode("utf-8").split(chr(0)) if item]
    return sorted(paths, key=str.casefold)


def category(path: str) -> str:
    first = path.split("/", 1)[0]
    return {
        "backend": "Backend (.NET)",
        "frontend": "Frontend (Angular)",
        "ai-engine": "Python AI research prototype",
        "docs": "Architecture and project documentation",
        "Notes": "Learning notes",
        "scripts": "Documentation tooling",
        ".github": "GitHub automation",
    }.get(first, "Root files and configuration")


def render_inventory(paths: list[str]) -> str:
    groups: dict[str, list[str]] = {}
    order = [
        "Root files and configuration",
        "Backend (.NET)",
        "Frontend (Angular)",
        "Python AI research prototype",
        "Architecture and project documentation",
        "Learning notes",
        "Documentation tooling",
        "GitHub automation",
    ]
    for path in paths:
        groups.setdefault(category(path), []).append(path)

    lines = [
        "<!-- Generated by scripts/check_architecture_docs.py; do not edit manually. -->",
        "# Generated Repository Source Inventory",
        "",
        "This file is generated from the non-ignored Git working tree so newly added source files can be indexed before staging.",
        "It is a discovery index, not a substitute for reading source code. Regenerate with",
        BT + "python scripts/check_architecture_docs.py --write" + BT + " and verify with " +
        BT + "python scripts/check_architecture_docs.py --check" + BT + ".",
        "",
        f"Files indexed: **{len(paths)}**",
        "",
    ]
    for group in order:
        items = groups.get(group, [])
        if not items:
            continue
        lines.extend([f"## {group}", "", *[f"- {BT}{item}{BT}" for item in items], ""])
    return "\n".join(lines).rstrip() + "\n"


def render_project_map() -> str:
    project_files = sorted((ROOT / "backend").rglob("*.csproj"))
    names = {p.resolve(): p.stem for p in project_files}
    refs: set[tuple[str, str]] = set()
    for project in project_files:
        root = ET.parse(project).getroot()
        for item in root.iter():
            if item.tag.split("}")[-1] != "ProjectReference":
                continue
            include = item.attrib.get("Include")
            if not include:
                continue
            target = (project.parent / include.replace("\\", "/")).resolve()
            if target in names:
                refs.add((project.stem, names[target]))

    descriptions = {
        "API": "ASP.NET Core host",
        "Application": "Use cases and MediatR",
        "Core": "Domain entities and rules",
        "Infrastructure": "Persistence, providers and adapters",
    }
    lines = [
        "<!-- Generated by scripts/check_architecture_docs.py; do not edit manually. -->",
        "# Generated .NET Project Dependency Map",
        "",
        "Generated from ProjectReference entries in the backend .csproj files. Arrows mean compile-time project references, not runtime request direction.",
        "",
        FENCE + "mermaid",
        "flowchart TD",
    ]
    for project in sorted(names.values()):
        label = descriptions.get(project, project)
        lines.append(f'  {project}["{project}<br/>{label}"]')
    for source, target in sorted(refs):
        lines.append(f"  {source} --> {target}")
    lines.extend([FENCE, ""])
    return "\n".join(lines)


def markdown_files() -> list[Path]:
    found: set[Path] = {p for p in TOP_LEVEL_DOCS if p.exists()}
    for root in DOC_ROOTS:
        if root.exists():
            found.update(p for p in root.rglob("*.md") if p.is_file())
    return sorted(found)


def validate_fences(path: Path, content: str) -> list[str]:
    errors: list[str] = []
    fence_lines = [line for line in content.splitlines() if line.lstrip().startswith(FENCE)]
    if len(fence_lines) % 2:
        errors.append(f"{path.relative_to(ROOT)}: unbalanced Markdown code fences")
    return errors


def validate_backtick_paths(path: Path, content: str) -> list[str]:
    errors: list[str] = []
    prefixes = ("backend/", "frontend/", "ai-engine/", "docs/", "Notes/", "scripts/", ".github/")
    pattern = re.escape(BT) + r"([^" + re.escape(BT) + r"\n]+)" + re.escape(BT)
    for match in re.finditer(pattern, content):
        token = match.group(1).strip()
        if not token.startswith(prefixes):
            continue
        candidate = token.rstrip(".,;:!?)]}").rstrip("/")
        if not candidate:
            continue
        if any(char in candidate for char in "*?[]"):
            exists = bool(glob.glob(str(ROOT / candidate), recursive=True))
        else:
            exists = (ROOT / candidate).exists()
        if not exists:
            errors.append(
                f"{path.relative_to(ROOT)}: referenced path does not exist: {BT}{candidate}{BT}"
            )
    return errors


def check_generated(path: Path, expected: str) -> list[str]:
    if not path.exists():
        return [
            f"{path.relative_to(ROOT)} is missing. Run "
            + BT + "python scripts/check_architecture_docs.py --write" + BT + "."
        ]
    if path.read_text(encoding="utf-8") != expected:
        return [
            f"{path.relative_to(ROOT)} is stale. Run "
            + BT + "python scripts/check_architecture_docs.py --write" + BT
            + ", review the diff, and commit it."
        ]
    return []


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate generated architecture files")
    mode.add_argument("--check", action="store_true", help="fail if generated files or references are stale")
    args = parser.parse_args()

    try:
        paths = working_tree_paths()
        expected_inventory = render_inventory(paths)
        expected_project_map = render_project_map()
    except (OSError, subprocess.CalledProcessError, ET.ParseError) as exc:
        print(f"ERROR: could not generate architecture files: {exc}", file=sys.stderr)
        return 2

    if args.write:
        INVENTORY.parent.mkdir(parents=True, exist_ok=True)
        INVENTORY.write_text(expected_inventory, encoding="utf-8")
        PROJECT_MAP.write_text(expected_project_map, encoding="utf-8")
        print(f"Wrote {INVENTORY.relative_to(ROOT)} ({len(paths)} paths).")
        print(f"Wrote {PROJECT_MAP.relative_to(ROOT)}.")
    else:
        errors = check_generated(INVENTORY, expected_inventory)
        errors.extend(check_generated(PROJECT_MAP, expected_project_map))
        if errors:
            print("Generated architecture files are stale:")
            for error in errors:
                print(f"- {error}")
            return 1

    errors = []
    for doc in markdown_files():
        content = doc.read_text(encoding="utf-8")
        errors.extend(validate_fences(doc, content))
        errors.extend(validate_backtick_paths(doc, content))

    if errors:
        print("Architecture documentation checks failed:")
        for error in errors:
            print(f"- {error}")
        return 1

    print(f"Architecture documentation checks passed ({len(markdown_files())} Markdown files checked).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
